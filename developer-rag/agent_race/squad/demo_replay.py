"""OFFLINE demo of Week 10. No API key, no model calls, no quota: it replays the
REAL recorded runs (race_runs.json, traces.jsonl, failure_runs.json).

    python3 squad/demo_replay.py                 # default case: hard_04
    python3 squad/demo_replay.py --case medium_07
    python3 squad/demo_replay.py --list
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent


def load():
    runs = json.loads((HERE / "race_runs.json").read_text(encoding="utf-8"))["rows"]
    traces = [json.loads(l) for l in (HERE / "traces.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()]
    return runs, traces


def banner(t):
    print("\n" + "=" * 78 + f"\n{t}\n" + "=" * 78)


def show_calls(traces, trace_id):
    rows = [t for t in traces if t["trace_id"] == trace_id]
    print(f"{'#':>2}  {'who':<15}{'hand-off (what triggered this model call)':<50}{'prompt':>7}{'out':>6}{'total':>7}")
    for t in rows:
        print(f"{t['seq']:>2}  {t['caller']:<15}{t['handoff'][:49]:<50}{t['prompt_tokens']:>7}{t['completion_tokens']:>6}{t['total_tokens']:>7}")
    print(f"{'':>2}  {'TOTAL':<65}{sum(t['total_tokens'] for t in rows):>14}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--case", default="hard_04")
    ap.add_argument("--list", action="store_true")
    a = ap.parse_args()
    runs, traces = load()
    if a.list:
        print(sorted({r["race_id"] for r in runs}))
        return

    banner("1. WHAT WE COMPARED")
    print("Arm A: single agent (agent.py, 3 docs tools).  Arm B: manager + version worker + code worker.")
    print("Same questions, same judge, same model for every role (gpt-oss-20b), same ceilings.")

    banner(f"2. ONE QUESTION, BOTH ARMS: {a.case}")
    for arm in ("single", "squad"):
        r = next((x for x in runs if x["race_id"] == a.case and x["arm"] == arm), None)
        if not r:
            print(f"[{arm}] no finished run recorded for this case")
            continue
        print(f"\n--- {arm.upper()}: status={r['status']} verdict={r['verdict']} tokens={r['total_tokens']:,} "
              f"cost=${r['total_cost_usd']:.5f} delegations={r['delegations']}")
        show_calls(traces, r["trace_id"])
        print("ANSWER:", (r["answer"] or "(no answer: budget hit)")[:300])

    banner("3. WHERE THE SQUAD'S TOKENS GO (context re-send, by hand-off, all recorded squad runs)")
    final = {r["trace_id"] for r in runs if r["arm"] == "squad"}
    agg = defaultdict(int)
    for t in traces:
        if t["trace_id"] in final:
            h = t["handoff"].replace("tool-loop lap 2", "tool-loop (lap 2+)")
            for n in range(3, 9):
                h = h.replace(f"tool-loop lap {n}", "tool-loop (lap 2+)")
            agg[h] += t["total_tokens"]
    total = sum(agg.values())
    for h, v in sorted(agg.items(), key=lambda kv: -kv[1]):
        print(f"  {v:>7,}  {100 * v / total:5.1f}%  {h}")
    print("  Read: the biggest cost is a worker re-reading the docs it just fetched; workers hand back")
    print("  short summaries, so the manager's own re-send stays smaller.")

    banner("4. THE RACE TABLE (generated by analyze.py)")
    print((HERE / "race_table.md").read_text(encoding="utf-8").split("## Per repeat")[0])
    print((HERE / "multiplier.txt").read_text(encoding="utf-8"))

    banner("5. INJECTED 500 ON THE VERSION WORKER (hard_04)")
    f = json.loads((HERE / "failure_runs.json").read_text(encoding="utf-8"))
    for run in f["runs"]:
        print(f"\n[{run['mode']}] version-worker call statuses: {run['version_worker_statuses']}  "
              f"graded vs golden: {run['verdict_vs_golden']}  tokens: {run['total_tokens']:,}")
        print("  ANSWER:", run["answer"][:260].replace("\n", " "), "...")
    print("\n  persistent = it kept calling the dead worker, then answered confidently WITHOUT a verified version check = LIED")
    print("  transient  = retried once, got a good result = recovered")

    banner("6. VERDICT")
    print((HERE / "verdict.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
